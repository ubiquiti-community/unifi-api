package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestWriteGeneratorConfig(t *testing.T) {
	resources := sampleResources()

	outDir := filepath.Join(t.TempDir(), "openapi-generator")
	require.NoError(t, WriteGeneratorConfig(resources, outDir))

	goNames, err := os.ReadFile(filepath.Join(outDir, "go-name-mappings.cfg"))
	require.NoError(t, err)
	assert.Contains(t, string(goNames), "name=Name")
	assert.Contains(t, string(goNames), "vlan=VLAN")

	modelNames, err := os.ReadFile(filepath.Join(outDir, "model-name-mappings.cfg"))
	require.NoError(t, err)
	assert.Contains(t, string(modelNames), "Network=Network")
	assert.Contains(t, string(modelNames), "NetworkGateway=NetworkGateway")

	fileMap, err := os.ReadFile(filepath.Join(outDir, "model-file-mappings.cfg"))
	require.NoError(t, err)
	assert.Contains(t, string(fileMap), "NetworkGateway=Network")
	// Synthesized Device schemas get their ownership assigned directly.
	assert.Contains(t, string(fileMap), "DevicePortTable=Device")
	assert.Contains(t, string(fileMap), "DeviceState=Device")
}

func TestWriteGeneratorConfigIDCollision(t *testing.T) {
	// A resource with both "_id" -> ID (added by NewResource) and a plain
	// "id" -> ID mapping should have the latter remapped to "Id" to avoid a
	// duplicate Go field/method.
	r := NewResource("Widget", "widgets")
	r.Types[r.StructName].Fields["ExtraID"] = NewFieldInfo("ID", "id", String, "", true, false, false, "")

	outDir := filepath.Join(t.TempDir(), "openapi-generator")
	require.NoError(t, WriteGeneratorConfig([]*ResourceInfo{r}, outDir))

	goNames, err := os.ReadFile(filepath.Join(outDir, "go-name-mappings.cfg"))
	require.NoError(t, err)
	assert.Contains(t, string(goNames), "id=Id")
	assert.Contains(t, string(goNames), "_id=ID")
}

func TestWriteGeneratorConfigDuplicateFieldNameWarning(t *testing.T) {
	r := NewResource("Widget", "widgets")
	r.Types[r.StructName].Fields["A"] = NewFieldInfo("FieldA", "same_json", String, "", true, false, false, "")
	r.Types[r.StructName].Fields["B"] = NewFieldInfo("FieldB", "same_json", String, "", true, false, false, "")

	outDir := filepath.Join(t.TempDir(), "openapi-generator")
	// The first writer for a JSON name wins; this should not error.
	require.NoError(t, WriteGeneratorConfig([]*ResourceInfo{r}, outDir))
}

func TestWriteGeneratorConfigConflictingModelOwnerWarning(t *testing.T) {
	a := NewResource("Alpha", "alpha")
	a.Types["Shared"] = NewFieldInfo("Shared", "shared", "struct", "", false, false, false, "")

	b := NewResource("Beta", "beta")
	b.Types["Shared"] = NewFieldInfo("Shared", "shared", "struct", "", false, false, false, "")

	outDir := filepath.Join(t.TempDir(), "openapi-generator")
	// Should not error; a warning is printed and the first owner wins.
	require.NoError(t, WriteGeneratorConfig([]*ResourceInfo{a, b}, outDir))

	data, err := os.ReadFile(filepath.Join(outDir, "model-file-mappings.cfg"))
	require.NoError(t, err)
	assert.Contains(t, string(data), "Shared=Alpha")
}

func TestWriteGeneratorConfigInvalidOutDir(t *testing.T) {
	blocker := filepath.Join(t.TempDir(), "blocker")
	require.NoError(t, os.WriteFile(blocker, []byte("x"), 0o644))

	err := WriteGeneratorConfig(sampleResources(), filepath.Join(blocker, "cfg"))
	assert.Error(t, err)
}

func TestWriteMappingFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "map.cfg")
	require.NoError(t, writeMappingFile(path, "Test header.", map[string]string{"b": "2", "a": "1"}))

	data, err := os.ReadFile(path)
	require.NoError(t, err)
	lines := strings.Split(strings.TrimRight(string(data), "\n"), "\n")
	require.Len(t, lines, 4)
	assert.Equal(t, "# Test header.", lines[0])
	assert.Equal(t, "# Generated by cmd/fields from the UniFi field definitions. DO NOT EDIT.", lines[1])
	assert.Equal(t, "a=1", lines[2])
	assert.Equal(t, "b=2", lines[3])
}

func TestWriteMappingFileInvalidPath(t *testing.T) {
	err := writeMappingFile(filepath.Join(t.TempDir(), "missing-dir", "map.cfg"), "h", map[string]string{})
	assert.Error(t, err)
}
